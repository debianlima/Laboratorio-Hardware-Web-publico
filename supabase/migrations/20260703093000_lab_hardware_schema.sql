-- Supabase/PostgreSQL schema for Laboratorio de Hardware 2025
-- Converted from docker/mysql/init.sql.
-- Uses a dedicated schema to avoid conflicts with existing public tables.

CREATE SCHEMA IF NOT EXISTS lab_hardware;

CREATE TABLE IF NOT EXISTS lab_hardware.usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    tipo VARCHAR(20) NOT NULL DEFAULT 'padrao' CHECK (tipo IN ('administrador', 'padrao')),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS lab_hardware.laboratorios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    lugar VARCHAR(100) NOT NULL,
    nome VARCHAR(100) NOT NULL,
    tipo VARCHAR(30) NOT NULL DEFAULT 'informatica_normal' CHECK (tipo IN ('redes', 'hardware', 'robotica', 'informatica_normal')),
    tecnico_responsavel VARCHAR(100),
    informacao_adicional TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS lab_hardware.equipamentos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    descricao TEXT,
    quantidade INTEGER NOT NULL DEFAULT 1 CHECK (quantidade >= 0),
    disponivel INTEGER NOT NULL DEFAULT 1 CHECK (disponivel >= 0),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS lab_hardware.tipos_itens (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS lab_hardware.emprestimos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES lab_hardware.usuarios(id) ON DELETE CASCADE,
    equipamento_id INTEGER NOT NULL REFERENCES lab_hardware.equipamentos(id) ON DELETE CASCADE,
    data_emprestimo TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_devolucao TIMESTAMPTZ NULL DEFAULT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'devolvido', 'atrasado')),
    observacao TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS lab_hardware.agendamentos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES lab_hardware.usuarios(id) ON DELETE CASCADE,
    laboratorio_id INTEGER NOT NULL REFERENCES lab_hardware.laboratorios(id) ON DELETE CASCADE,
    data_inicio TIMESTAMPTZ NOT NULL,
    data_fim TIMESTAMPTZ NOT NULL,
    finalidade VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'aprovado', 'cancelado', 'concluido')),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (data_fim > data_inicio)
);

CREATE TABLE IF NOT EXISTS lab_hardware.itens (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_patrimonio VARCHAR(50) NOT NULL UNIQUE,
    nome VARCHAR(100) NOT NULL,
    tipo_id INTEGER REFERENCES lab_hardware.tipos_itens(id) ON DELETE SET NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'disponivel' CHECK (status IN ('disponivel', 'emprestado', 'manutencao')),
    descricao TEXT,
    localizacao VARCHAR(100),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS lab_hardware.login_attempts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip_address VARCHAR(45) NOT NULL,
    username VARCHAR(50) NOT NULL,
    attempted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    success BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_lab_emprestimos_usuario ON lab_hardware.emprestimos(usuario_id);
CREATE INDEX IF NOT EXISTS idx_lab_emprestimos_equipamento ON lab_hardware.emprestimos(equipamento_id);
CREATE INDEX IF NOT EXISTS idx_lab_emprestimos_status ON lab_hardware.emprestimos(status);
CREATE INDEX IF NOT EXISTS idx_lab_agendamentos_usuario ON lab_hardware.agendamentos(usuario_id);
CREATE INDEX IF NOT EXISTS idx_lab_agendamentos_laboratorio ON lab_hardware.agendamentos(laboratorio_id);
CREATE INDEX IF NOT EXISTS idx_lab_itens_tipo ON lab_hardware.itens(tipo_id);
CREATE INDEX IF NOT EXISTS idx_lab_itens_status ON lab_hardware.itens(status);
CREATE INDEX IF NOT EXISTS idx_lab_login_attempts_ip_time ON lab_hardware.login_attempts(ip_address, attempted_at);
CREATE INDEX IF NOT EXISTS idx_lab_login_attempts_username ON lab_hardware.login_attempts(username);

CREATE OR REPLACE FUNCTION lab_hardware.set_atualizado_em()
RETURNS TRIGGER AS $$
BEGIN
    NEW.atualizado_em = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_usuarios_atualizado_em ON lab_hardware.usuarios;
CREATE TRIGGER trg_usuarios_atualizado_em BEFORE UPDATE ON lab_hardware.usuarios FOR EACH ROW EXECUTE FUNCTION lab_hardware.set_atualizado_em();

