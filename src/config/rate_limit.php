<?php
require_once __DIR__ . '/db.php';

define('MAX_LOGIN_ATTEMPTS', 5);
define('RATE_LIMIT_WINDOW', 900);
define('BLOCK_DURATION', 900);

function ensureLoginAttemptsTable($conn): void
{
    if (usarPostgres()) {
        $conn->query("CREATE TABLE IF NOT EXISTS login_attempts (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ip_address VARCHAR(45) NOT NULL,
            username VARCHAR(50) NOT NULL,
            attempted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            success BOOLEAN NOT NULL DEFAULT FALSE
        )");
        $conn->query("CREATE INDEX IF NOT EXISTS idx_lab_login_attempts_ip_time ON login_attempts(ip_address, attempted_at)");
        $conn->query("CREATE INDEX IF NOT EXISTS idx_lab_login_attempts_username ON login_attempts(username)");
        return;
    }

    $conn->query("CREATE TABLE IF NOT EXISTS login_attempts (
        id INT AUTO_INCREMENT PRIMARY KEY,
        ip_address VARCHAR(45) NOT NULL,
        username VARCHAR(50) NOT NULL,
        attempted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        success TINYINT(1) NOT NULL DEFAULT 0,
        INDEX idx_ip_time (ip_address, attempted_at),
        INDEX idx_username (username)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");
}

function getClientIp(): string
{
    $sources = ['HTTP_X_FORWARDED_FOR', 'HTTP_X_REAL_IP', 'REMOTE_ADDR'];
    foreach ($sources as $source) {
        if (!empty($_SERVER[$source])) {
            $ip = explode(',', $_SERVER[$source])[0];
            if (filter_var(trim($ip), FILTER_VALIDATE_IP)) {
                return trim($ip);
            }
        }
    }
    return $_SERVER['REMOTE_ADDR'] ?? '0.0.0.0';
}

function isRateLimited(string $ip): bool
{
    $conn = conectar();
    if (!$conn) return false;
    ensureLoginAttemptsTable($conn);

    $window = date('Y-m-d H:i:s', time() - RATE_LIMIT_WINDOW);
    $successCondition = usarPostgres() ? 'success = false' : 'success = 0';
    $stmt = $conn->prepare(
        "SELECT COUNT(*) as total FROM login_attempts
         WHERE ip_address = ? AND attempted_at >= ? AND {$successCondition}"
    );
    $stmt->bind_param('ss', $ip, $window);
    $stmt->execute();
    $result = $stmt->get_result()->fetch_assoc();
    $stmt->close();
    $conn->close();

    return ($result['total'] ?? 0) >= MAX_LOGIN_ATTEMPTS;
}

function logLoginAttempt(string $ip, string $username, bool $success): void
{
    $conn = conectar();
    if (!$conn) return;
    ensureLoginAttemptsTable($conn);

    $stmt = $conn->prepare(
        'INSERT INTO login_attempts (ip_address, username, success) VALUES (?, ?, ?)'
    );

    if (usarPostgres()) {
        $successBool = $success;
        $stmt->bind_param('sss', $ip, $username, $successBool);
    } else {
        $successInt = $success ? 1 : 0;
        $stmt->bind_param('ssi', $ip, $username, $successInt);
    }

    $stmt->execute();
    $stmt->close();
    $conn->close();
}

function getRemainingAttempts(string $ip): int
{
    $conn = conectar();
    if (!$conn) return MAX_LOGIN_ATTEMPTS;
    ensureLoginAttemptsTable($conn);

    $window = date('Y-m-d H:i:s', time() - RATE_LIMIT_WINDOW);
    $successCondition = usarPostgres() ? 'success = false' : 'success = 0';
    $stmt = $conn->prepare(
        "SELECT COUNT(*) as total FROM login_attempts
         WHERE ip_address = ? AND attempted_at >= ? AND {$successCondition}"
    );
    $stmt->bind_param('ss', $ip, $window);
    $stmt->execute();
    $result = $stmt->get_result()->fetch_assoc();
    $stmt->close();
    $conn->close();

    $failed = $result['total'] ?? 0;
    return max(0, MAX_LOGIN_ATTEMPTS - $failed);
}
